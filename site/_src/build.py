def render(name: str) -> str:
    spec = dict(PAGES[name])
    body = SRC.joinpath(spec.pop("page")).read_text()
    body = fill(body, steps=render_steps(), cards=render_cards()) if "{{" in body else body
    head = fill(partial("head"), **{k: spec[k] for k in
                                    ("title", "description", "og_title", "og_description")})
    header = fill(partial("header"), **{k: spec[k] for k in ("top_class", "lockup", "nav")})
    footer = fill(partial("footer"), footer_links=spec["footer_links"])
    tail = ("\n" + spec["scripts"] + "\n") if spec["scripts"] else "\n"
    return BANNER + head + "\n" + header + "\n" + body + footer + tail + "</body>\n</html>\n"


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for name in PAGES:
        built = render(name)
        target = OUT / name
        if check:
            if not target.exists() or target.read_text() != built:
                stale.append(name)
        else:
            target.write_text(built)
            print(f"wrote {name} ({len(built):,} bytes)")
    if check:
        if stale:
            print("out of date: " + ", ".join(stale))
            print("run: python3 site/_src/build.py")
            return 1
        print("pages are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
